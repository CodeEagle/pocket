import { strict as assert } from "node:assert";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { test } from "bun:test";
import { buildGuest } from "../../../sdk/scripts/build_guest.ts";
import { NativeSession, textOf, type Frame } from "./native_session.ts";

test("one Core paragraph keeps reveal geometry and hits the second rectangle of a wrapped link", async () => {
  const repo = resolve(import.meta.dir, "../../..");
  const out = process.env.POCKET_INLINE_TEXT_EVIDENCE ?? resolve(repo, "sdk/.pocket-build/inline-text-native");
  const built = await buildGuest({ projectRoot: resolve(import.meta.dir, "fixtures/inline-text"), outDir: resolve(out, "guest"), tickHz: 60, rasterDensity: 1 });
  const metadata = JSON.parse(readFileSync(built.metadata, "utf8"));
  const session = new NativeSession({ bytecodePath: built.bytecode, pakPath: built.pak, metadataPath: built.metadata, runtimeAbi: metadata.runtimeAbi }, { width: 390, height: 600 });
  const evidence: { name: string; frame: Frame }[] = [];
  const layoutOf = (frame: Frame) => frame.ops?.find(op => /^Layout /.test(op.text ?? ""))?.text;
  try {
    let frame = await session.settle(await session.boot(), 4);
    const fullLayout = layoutOf(frame);
    mkdirSync(out, { recursive: true });
    writeFileSync(resolve(out, "initial-frame.json"), JSON.stringify(frame, null, 2));
    assert.ok(fullLayout && !/Layout 0 0 0/.test(fullLayout), "hidden source already has its full Core layout");
    assert.ok(textOf(frame).includes("Link rectangles 0"));
    evidence.push({ name: "hidden-full-layout", frame });
    frame = await session.tap("Reveal three", frame);
    assert.equal(layoutOf(frame), fullLayout);
    assert.ok(!frame.ops?.some(op => op.text === "reed"), "ruby stays hidden before its whole base is revealed");
    frame = await session.tap("Reveal four", frame);
    assert.equal(layoutOf(frame), fullLayout);
    assert.ok(frame.ops?.some(op => op.text === "reed"), "ruby appears at the exact base boundary");
    assert.ok(textOf(frame).includes("Link rectangles 0"), "partial source exposes no link hit geometry");
    frame = await session.tap("Reveal all", frame);
    assert.equal(layoutOf(frame), fullLayout);
    const second = frame.ops?.find(op => /^Rect 1 /.test(op.text ?? ""))?.text;
    assert.ok(second, "a long link wraps into at least two Core rectangles");
    const [x, y, width, height] = second.slice("Rect 1 ".length).split(" ").map(Number);
    assert.ok([x, y, width, height].every(Number.isFinite) && width! > 0 && height! > 0);
    evidence.push({ name: "wrapped-core-rectangles", frame });
    frame = await session.tapPoint({ x: 16 + x! + width! / 2, y: 180 + y! + height! / 2 });
    assert.ok(textOf(frame).includes("Link clicks 1"), "the second rectangle delivers a real pointer press to its link callback");
    assert.ok(textOf(frame).includes("Background clicks 0"), "a revealed link does not bubble to the parent reveal target");
    evidence.push({ name: "second-rectangle-pointer", frame });
    frame = await session.tap("Reveal three", frame);
    assert.ok(textOf(frame).includes("Link rectangles 0"));
    frame = await session.tapPoint({ x: 16 + x! + width! / 2, y: 180 + y! + height! / 2 });
    assert.ok(textOf(frame).includes("Link clicks 1") && textOf(frame).includes("Background clicks 1"), "hidden suffix has no stale link hit target to swallow the parent reveal press");
    evidence.push({ name: "hidden-link-parent-pointer", frame });
    frame = await session.tap("Switch source at same reveal", frame);
    assert.ok(textOf(frame).includes("Source replacement · reveal 3"), "the source swap leaves the current reveal count unchanged");
    assert.ok(textOf(frame).includes("Link ids replacement-note"), "the replacement run is visible at the same reveal value after Core resets its source cursor");
    assert.ok(textOf(frame).includes("Link rectangles 1"), "the fully revealed replacement range produces native link hit geometry");
    evidence.push({ name: "source-and-runs-change-at-same-reveal", frame });
    frame = await session.tap("Batch width", frame);
    assert.ok(textOf(frame).includes("Immediate width 240"), "getLayout synchronizes a changed explicit width inside the same Solid batch");
    assert.match(layoutOf(frame)!, /^Layout 240 /);
    evidence.push({ name: "synchronous-batch-width-query", frame });
    mkdirSync(out, { recursive: true });
    writeFileSync(resolve(out, "frames.json"), JSON.stringify({ fullLayout, secondRectangle: [x, y, width, height], evidence }, null, 2));
  } finally { await session.quit(); }
}, 180_000);
