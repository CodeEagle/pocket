import { clickNovelHistory } from "./novel_browser_helpers.ts";
import { strict as assert } from "node:assert";
import { mkdtemp, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import { chromium } from "playwright";
import { test } from "bun:test";
import { startEditor } from "../server.ts";

test("Editor saves variable lifetimes and JSON defaults, preserves metadata and executes new-game semantics", { timeout: 45_000 }, async () => {
  const temporary = await mkdtemp(join(tmpdir(), "pocket-variables-browser-"));
  const project = join(temporary, "project");
  const id = "variables-browser";
  await mkdir(project);
  await writeFile(join(project, "pocket.json"), JSON.stringify({ pocket: 2, id: "test.variables", name: id, app: { entry: "app.tsx", framework: "solid" } }));
  await writeFile(join(project, "editor.json"), JSON.stringify({ id, appId: "test.variables", name: id, version: "0.1.0" }));
  const story = { id, version: 1, start: "start", variableDefinitions: { _memory: { lifetime: "save", defaultValue: 0, custom: { author: "retained" } } }, script: { start: [{ type: "input", id: "memory", variable: "_memory", inputType: "number", prompt: "Memory" }, { type: "ending", id: "end" }] } };
  await writeFile(join(project, "story.json"), JSON.stringify(story));
  await writeFile(join(project, "novel.assets.json"), JSON.stringify({ backgrounds: {}, characters: {}, cgs: {}, audio: {} }));
  const server = await startEditor({ port: 0, updatePort: 0, workspace: join(temporary, "workspace"), projectRoot: project });
  const browser = await chromium.launch({ headless: true });
  const page = await browser.newPage();
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  const origin = `http://127.0.0.1:${server.port}`;
  try {
    await page.goto(`${origin}/novel?project=${id}`);
    await page.getByRole("button", { name: "变量声明", exact: true }).click();
    await page.getByLabel("生命周期 _memory", { exact: true }).selectOption("persistent");
    await page.getByLabel("默认值 _memory", { exact: true }).fill("7");
    await page.getByLabel("默认值 _memory", { exact: true }).press("Tab");
    page.once("dialog", dialog => dialog.accept("_session"));
    await page.getByRole("button", { name: "添加变量声明", exact: true }).click();
    await page.getByLabel("生命周期 _session", { exact: true }).selectOption("session");
    await page.getByRole("button", { name: "设置默认值 _session", exact: true }).click();
    await page.getByLabel("默认值 _session", { exact: true }).fill('{"visits":1}');
    await page.getByLabel("默认值 _session", { exact: true }).press("Tab");
    page.once("dialog", dialog => dialog.accept("__proto__"));
    await page.getByRole("button", { name: "添加变量声明", exact: true }).click();
    assert.equal(await page.getByLabel("生命周期 __proto__", { exact: true }).inputValue(), "save");
    await page.getByRole("button", { name: "删除声明 __proto__", exact: true }).click();
    await page.getByRole("button", { name: "删除声明 _memory", exact: true }).click();
    await clickNovelHistory(page, "undo");
    assert.equal(await page.getByLabel("生命周期 _memory", { exact: true }).inputValue(), "persistent");
    await page.locator("#novel-save").click();
    await page.waitForFunction(() => document.querySelector("#novel-save-state")?.textContent === "已保存");
    const saved = JSON.parse(await readFile(join(project, "story.json"), "utf8"));
    assert.deepEqual(saved.variableDefinitions, { _memory: { lifetime: "persistent", defaultValue: 7, custom: { author: "retained" } }, _session: { lifetime: "session", defaultValue: { visits: 1 } } });
    await page.reload();
    await page.getByRole("button", { name: "变量声明", exact: true }).click();
    assert.equal(await page.getByLabel("生命周期 _session", { exact: true }).inputValue(), "session");
    const invalid = structuredClone(saved);
    invalid.variableDefinitions._memory.lifetime = "unknown";
    const rejected = await fetch(`${origin}/api/projects/${id}/novel/story`, { method: "PUT", headers: { "content-type": "application/json", "x-pocket-editor": "1" }, body: JSON.stringify(invalid) });
    assert.equal(rejected.status, 422);
    assert.deepEqual(JSON.parse(await readFile(join(project, "story.json"), "utf8")), saved);
    const runtimeFile = join(temporary, "runtime.mjs");
    await writeFile(runtimeFile, await (await fetch(`${origin}/api/projects/${id}/novel/runtime.js`)).text());
    const runtime = await import(pathToFileURL(runtimeFile).href);
    const engine = runtime.createNovelEngine(saved);
    engine.start(); engine.updateInput("42"); engine.submitInput();
    assert.equal(engine.getSnapshot().variables._memory, 42);
    engine.newGame();
    assert.equal(engine.getSnapshot().active.kind, "input");
    assert.equal(engine.getSnapshot().variables._memory, 42);
    assert.equal(engine.getSnapshot().variables._session.visits, 1);
    assert.equal(engine.getSnapshot().meta.persistentVariables._memory, 42);
    engine.dispose();
    assert.deepEqual(errors, []);
  } finally {
    await browser.close(); await server.stop(true);
    await rm(temporary, { recursive: true, force: true });
  }
});
