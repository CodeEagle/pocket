export function resolveDataKey(channel) {
  const key = typeof channel === 'number' ? channel : channels[channel] ?? DATA_KEY[channel];
  if (!Number.isInteger(key) || !Object.values(DATA_KEY).includes(key)) throw new RangeError(`Unsupported TFTC channel: ${channel}`);
  return key;
}

// Values are observed device facts. Unknown keys cannot be skipped safely because lengths vary.
export function decodeAttributes(payload) {
  const bytes = Array.from(payload);
  if (!bytes.every(value => Number.isInteger(value) && value >= 0 && value <= 255)) throw new RangeError("Attributes must contain bytes");
  const result = new Map();
  for (let offset = 0; offset < bytes.length;) {
    const key = bytes[offset++];
    if (!Object.values(DATA_KEY).includes(key)) throw new RangeError(`Unknown TFTC data key: ${key}`);
    const size = [0x23, 0x24, 0x25].includes(key) ? 2 : 1;
    if (offset + size > bytes.length) throw new RangeError('Truncated TFTC attribute');
    let value = bytes[offset++];
    if (size === 2) value |= bytes[offset++] << 8;
    result.set(key, value);
  }
  return result;
}

export function attributeSnapshot(attributes) {
  const result = Object.fromEntries([...attributes].map(([key, value]) => [key, value]));
  const compact = attributes.get(DATA_KEY.BATTERY_COMPACT_STATUS);
  const work = attributes.get(DATA_KEY.DEVICE_COMPACT_STATUS);
  const levels = Object.fromEntries(Object.entries({
    vibrationLevel: DATA_KEY.VIBRATION_LEVEL, telescopicLevel: DATA_KEY.TELESCOPIC_LEVEL,
    rotationLevel: DATA_KEY.ROTATION_LEVEL, suctionLevel: DATA_KEY.SUCTION_LEVEL,
    pulseLevel: DATA_KEY.PULSE_LEVEL, inflationLevel: DATA_KEY.INFLATION_LEVEL,
    speedLevel: DATA_KEY.SPEED_LEVEL, heatLevel: DATA_KEY.HEAT_LEVEL,
    swingSwitch: DATA_KEY.SWING_SWITCH,
  }).map(([name, key]) => [name, attributes.get(key) ?? null]));
  const batteryStatus = compact === undefined ? attributes.get(DATA_KEY.BATTERY_STATUS_INDEX) ?? null : compact & 3;
  return {
    ...levels,
    attributes: result,
    batteryStatusName: ['NORMAL', 'LOW_BATTERY', 'CHARGING', 'CHARGE_COMPLETE'][batteryStatus] ?? null,
    battery: compact === undefined ? attributes.get(DATA_KEY.BATTERY) ?? null : compact >>> 2,
    batteryStatus: compact === undefined ? attributes.get(DATA_KEY.BATTERY_STATUS_INDEX) ?? null : compact & 3,
    isWorking: work === undefined ? null : Boolean(work & 1),
    workModeState: work === undefined ? null : (work >>> 1) & 7,
    commandFlag: work === undefined ? null : work >>> 4,
  };
}
